print("""
Шаг 1.1. Любой магический 3x3 ассоциативен (стандартный факт, переписан здесь как
         тождество): при центре C каждая пара противоположных клеток даёт сумму 2C,
         а сам квадрат имеет вид, задаваемый двумя свободными параметрами x, y:

              C+x     C-x-y   C+y
              C-x+y    C      C+x-y
              C-y     C+x+y   C-x

         Никакого выбора семейства здесь ещё нет: это ОБЩИЙ магический 3x3.
""")

