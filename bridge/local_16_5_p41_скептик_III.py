def qr_set(p):
    """множество квадратов F_p, включая 0 — пересчитано с нуля"""
    return {(k * k) % p for k in range(p)}

def cells_mod(mm, nn, aa, bb, p):
    """пять однородных форм в F_p; s = (m^2+n^2)/2 берётся через обратный к 2"""
    inv2 = pow(2, p - 2, p)
    s = ((mm * mm + nn * nn) % p) * inv2 % p
    F0 = (mm * mm * bb * bb + nn * nn * aa * aa) % p
    F4 = s * (aa * aa + bb * bb) % p
    F8 = (nn * nn * bb * bb + mm * mm * aa * aa) % p
    two_mn_ab = (2 * mm * nn * aa * bb) % p
    L = (F4 - two_mn_ab) % p
    U = (F4 + two_mn_ab) % p
    return [F0, F4, F8, L, U]

def proj_points(p):
    """все p+1 точек P^1(F_p): (a:b) = (t:1) и (1:0)"""
    return [(k, 1) for k in range(p)] + [(1, 0)]

CELLNAMES = ["F0", "F4", "F8", "L", "U"]

def full_table(mm, nn, p, allow_zero=True, subset=(0, 1, 2, 3, 4), verbose=True):
    QR = qr_set(p)
    good = QR if allow_zero else (QR - {0})
    survivors = []
    rows = []
    for (aa, bb) in proj_points(p):
        v = cells_mod(mm, nn, aa, bb, p)
        okf = [v[i] in good for i in subset]
        rows.append(((aa, bb), v, okf, all(okf)))
        if all(okf):
            survivors.append(((aa, bb), v))
    if verbose:
        hdr = "  (a:b)      " + "".join(f"{CELLNAMES[i]:>7s}" for i in subset) + "   |  квадрат?              | выжил"
        print(hdr)
        print("  " + "-" * (len(hdr) - 2))
        for ((aa, bb), v, okf, allok) in rows:
            lbl = f"({aa}:{bb})" if bb == 0 else f"t={aa}"
            vals = "".join(f"{v[i]:7d}" for i in subset)
            flags = " ".join("да " if f else "НЕТ" for f in okf)
            print(f"  {lbl:10s}{vals}   |  {flags:22s} | {'ДА' if allok else '-'}")
    return survivors

