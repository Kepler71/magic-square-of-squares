def vp(xx, p):
    if xx == 0:
        return None
    num, den = xx.numerator, xx.denominator
    v = 0
    while num % p == 0:
        num //= p; v += 1
    while den % p == 0:
        den //= p; v -= 1
    return v

def is_sq_Qp(xx, p):
    if xx == 0:
        return True
    v = vp(xx, p)
    if v % 2:
        return False
    yy = xx / Fr(p) ** v
    u = (yy.numerator * pow(yy.denominator, p - 2, p)) % p
    return pow(u, (p - 1) // 2, p) == 1

def cells_Q(mm, nn, tt):
    s = Fr(mm * mm + nn * nn, 2)
    return [Fr(mm * mm) + Fr(nn * nn) * tt * tt,
            s * (1 + tt * tt),
            Fr(nn * nn) + Fr(mm * mm) * tt * tt,
            s * (1 + tt * tt) - 2 * mm * nn * tt,
            s * (1 + tt * tt) + 2 * mm * nn * tt]

